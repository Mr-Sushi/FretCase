// Generates TypeScript types from shared/schema and copies the example data the mock mode needs.
// Reads ../shared (read-only), writes only into app/src/generated.
import { compile } from 'json-schema-to-typescript'
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const shared = join(here, '..', '..', 'shared')
const out = join(here, '..', 'src', 'generated')
mkdirSync(out, { recursive: true })

const banner = '/* Generated by scripts/sync-shared.mjs from shared/schema. Do not edit. */'
for (const [file, name] of [['song.schema.json', 'song'], ['panel-events.schema.json', 'panel']]) {
  const schema = JSON.parse(readFileSync(join(shared, 'schema', file), 'utf8'))
  const ts = await compile(schema, schema.title, { bannerComment: banner, additionalProperties: false, unreachableDefinitions: true, strictIndexSignatures: false })
  writeFileSync(join(out, `${name}.ts`), ts)
}
copyFileSync(join(shared, 'schema', 'examples', 'song.json'), join(out, 'example-song.json'))
copyFileSync(join(shared, 'data', 'rhythm-presets.json'), join(out, 'rhythm-presets.json'))
console.log('generated types and data into src/generated')
